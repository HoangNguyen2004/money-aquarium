import assert from 'node:assert/strict';
import { createGoal, contribute, contributed, goalProgress, goalStage } from '../savings';
import { feedAquarium, migrateGame, newGame, review, settle, start, type Ctx } from './rules';
import { habitStreak, waterStatus } from './finance';
import { CATALOG } from './catalog';
import type { Transaction } from '../types';
const day='2026-11-15';
const tx=(id:string,date=day,amount=1000):Transaction=>({id,date,amount,type:'expense',category:'food',note:'',createdAt:0,source:'manual'});
const ctx=(transactions:Transaction[],income=0):Ctx=>({transactions,plan:{income,savings:0},budgets:{}});
let game=start(newGame(),'Hồ Mây',day);
assert.equal(game.food,6);
game=settle(game,Array.from({length:100},(_,i)=>tx(String(i))),day);
assert.equal(game.food,9);
assert.equal(settle(game,[tx('retry')],day).food,9);
assert.equal(settle(game,[],day).food,9);
assert.equal(settle(game,[tx('edited',day,10000000)],day).food,9);
const checked=review(game,ctx([]),day);
assert.equal(checked.food,11);
assert.equal(review(checked,ctx([]),day).food,11);
let fed=feedAquarium(checked,day);assert.ok(typeof fed!=='string');
assert.equal(fed.food,10);assert.equal(fed.fishCare?.['fish-gold'].days,1);
const again=feedAquarium(fed,day);assert.ok(typeof again!=='string');assert.equal(again.food,9);assert.equal(again.fishCare?.['fish-gold'].days,1);
assert.equal(typeof feedAquarium({...fed,food:0},day),'string');
assert.equal(typeof feedAquarium({...fed,hidden:['fish-gold']},day),'string');
const {food:_,...oldSave}=game;
const migrated=migrateGame(oldSave);assert.equal(migrated.food,6);assert.equal(migrateGame(migrated).food,6);
assert.deepEqual(migrated.items,game.items);
assert.equal(migrateGame({...game,food:0}).food,0);
assert.equal(waterStatus(ctx([]),day).state,'unset');
assert.equal(waterStatus(ctx([tx('a',day,1200000)],3000000),'2026-11-01').state,'steady'); // future transactions excluded
assert.equal(waterStatus(ctx([tx('a','2026-11-01',1200000)],3000000),'2026-11-01').state,'ahead');
assert.equal(waterStatus(ctx([tx('a','2026-11-01',1200000)],3000000),'2026-11-29').state,'steady');
assert.equal(waterStatus(ctx([tx('a',day,3100000)],3000000),day).state,'over');
assert.ok(waterStatus(ctx([tx('a',day,3100000)],3000000),day).health>=0.6);
assert.equal(habitStreak({...game,startedAt:'2026-11-01',reviewed:['2026-11-13','2026-11-14']},ctx([tx('a')]),day),3);
assert.equal(habitStreak({...game,startedAt:'2026-11-01',reviewed:['2026-11-13','2026-11-14']},ctx([]),day),2);
let goal=createGoal('g','Quỹ dự phòng',1000000,'fish-gold','2027-01-01');assert.ok(typeof goal!=='string');
assert.equal(goalProgress(goal),0);
let next=contribute(goal,'transfer-a',300000,day);assert.ok(typeof next!=='string');
assert.equal(contributed(next),300000);assert.equal(goalStage(next),1);
assert.equal(contribute(next,'transfer-a',300000,day),next);
assert.equal(typeof contribute(next,'invalid',-1,day),'string');
assert.equal(typeof createGoal('g','Quỹ',0,'fish-gold',''),'string');
assert.equal(typeof createGoal('g','Quỹ',1000,'fish-gold','2026-02-31'),'string');
next=contribute(next,'transfer-b',700000,day);assert.ok(typeof next!=='string');assert.equal(goalStage(next),3);
assert.equal(goalProgress(JSON.parse(JSON.stringify(next))),1);
assert.equal(goalProgress({...next,contributions:next.contributions.filter(e=>e.id!=='transfer-b')}),0.3);
assert.equal(CATALOG.length,20);assert.equal(new Set(CATALOG.map(i=>i.id)).size,20);
assert.equal(CATALOG.filter(i=>i.rarity==='Event').length,1);
console.log('finance aquarium: ok');
